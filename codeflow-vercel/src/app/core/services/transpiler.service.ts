import { Injectable } from '@angular/core';
import {
  ASTNode,
  Condition,
  Function,
  PYTHON_KEYWORDS,
  ShowPart,
  Variable,
  VariableType
} from '../models/ast.model';

const INDENT = '    ';

interface TranspileContext {
  varMap: Map<string, Variable>;
  funcMap: Map<string, Function>;
  indent: number;
  loopDepth: number;
}

@Injectable({ providedIn: 'root' })
export class TranspilerService {
  transpile(nodes: ASTNode[], variables: Variable[], functions: Function[]): string {
    const context: TranspileContext = {
      varMap: new Map(variables.map(variable => [variable.id, variable])),
      funcMap: new Map(functions.map(func => [func.id, func])),
      indent: 0,
      loopDepth: 0
    };

    const parts = [
      this.buildHeader(),
      this.buildVariableDeclarations(variables),
      this.buildFunctionDefinitions(functions, context),
      this.walkNodes(nodes || [], context)
    ];

    return parts.filter(Boolean).join('\n') + '\n';
  }

  private buildHeader(): string {
    const now = new Date().toISOString().replace('T', ' ').slice(0, 19);
    return `# Generated by CodeFlow — ${now}\n# -----------------------------------------------\n`;
  }

  private buildVariableDeclarations(variables: Variable[]): string {
    if (!variables.length) return '';
    return variables
      .map(variable => `${this.sanitizeName(variable.name)} = ${this.pyLiteral(variable.type, variable.value)}`)
      .join('\n') + '\n';
  }

  private buildFunctionDefinitions(functions: Function[], context: TranspileContext): string {
    if (!functions.length) return '';

    return functions.map(func => {
      const name = this.sanitizeName(func.name);
      const parameter = func.argVarId ? this.resolveName(func.argVarId, context) : '';
      const bodyContext: TranspileContext = { ...context, indent: 1, loopDepth: 0 };
      const body = this.walkNodes(func.children || [], bodyContext);
      const returnLine = func.returnVarId
        ? `${INDENT}return ${this.resolveName(func.returnVarId, context)}`
        : '';
      const bodyLines = [body, returnLine].filter(Boolean).join('\n') || `${INDENT}pass`;
      return `def ${name}(${parameter}):\n${bodyLines}`;
    }).join('\n\n') + '\n';
  }

  private walkNodes(nodes: ASTNode[], context: TranspileContext): string {
    if (!Array.isArray(nodes)) return '';
    return nodes
      .map(node => this.walkNode(node, context))
      .filter(Boolean)
      .join('\n');
  }

  private walkNode(node: ASTNode, context: TranspileContext): string {
    if (!node || !node.type) return '';
    switch (node.type) {
      case 'show': return this.handleShow(node, context);
      case 'read': return this.handleRead(node, context);
      case 'assign': return this.handleAssign(node, context);
      case 'if': return this.handleIf(node, context);
      case 'while': return this.handleWhile(node, context);
      case 'for': return this.handleFor(node, context);
      case 'loop': return this.handleLoop(node, context);
      case 'break': return this.handleBreak(node, context);
      case 'function_call': return this.handleFunctionCall(node, context);
      case 'empty': return '';
      default: return `${this.pad(context)}# [nodo desconocido: ${node.type}]`;
    }
  }

  private handleShow(node: ASTNode, context: TranspileContext): string {
    const data = node.data as { parts?: ShowPart[] };
    const parts = data.parts || [];
    if (!parts.length) return `${this.pad(context)}print("")`;

    const rendered = parts.map(part => {
      if (part.type === 'text') return `"${this.escapePyString(part.value || '')}"`;
      return this.resolveName(part.varId || '', context);
    });

    if (rendered.length === 1) {
      return `${this.pad(context)}print(${rendered[0]})`;
    }

    const expression = parts.map((part, index) => {
      const value = rendered[index];
      if (part.type === 'variable') {
        const type = this.resolveType(part.varId || '', context);
        return type === 'string' ? value : `str(${value})`;
      }
      return value;
    }).join(' + ');

    return `${this.pad(context)}print(${expression})`;
  }

  private handleRead(node: ASTNode, context: TranspileContext): string {
    const data = node.data as { targetVarId?: string; prompt?: string };
    const varId = data.targetVarId || '';
    const variableName = this.resolveName(varId, context);
    const type = this.resolveType(varId, context);
    const prompt = data.prompt ? `"${this.escapePyString(data.prompt)}"` : '""';

    if (type === 'number') {
      return `${this.pad(context)}${variableName} = float(input(${prompt}))`;
    }
    if (type === 'boolean') {
      return `${this.pad(context)}${variableName} = input(${prompt}).strip().lower() in ("si", "sí", "true", "verdadero", "1", "v")`;
    }
    return `${this.pad(context)}${variableName} = input(${prompt})`;
  }

  private handleAssign(node: ASTNode, context: TranspileContext): string {
    const data = node.data as {
      targetVarId?: string;
      operator?: string;
      expression?: { type: 'literal' | 'variable'; valueType?: VariableType; value?: unknown; varId?: string };
    };
    const target = this.resolveName(data.targetVarId || '', context);
    const operator = data.operator || '=';

    let rightSide = 'None';
    if (data.expression?.type === 'variable') {
      rightSide = this.resolveName(data.expression.varId || '', context);
    } else if (data.expression?.type === 'literal') {
      rightSide = this.pyLiteral(data.expression.valueType || 'string', data.expression.value);
    }

    return `${this.pad(context)}${target} ${operator} ${rightSide}`;
  }

  private handleIf(node: ASTNode, context: TranspileContext): string {
    const data = node.data as { condition?: Condition };
    const condition = this.buildCondition(data.condition, context);
    const childContext: TranspileContext = { ...context, indent: context.indent + 1 };
    const body = this.walkNodes(node.children || [], childContext) || `${this.pad(childContext)}pass`;

    let result = `${this.pad(context)}if ${condition}:\n${body}`;

    if (node.elseChildren !== null && node.elseChildren !== undefined) {
      const elseBody = this.walkNodes(node.elseChildren, childContext) || `${this.pad(childContext)}pass`;
      result += `\n${this.pad(context)}else:\n${elseBody}`;
    }

    return result;
  }

  private handleWhile(node: ASTNode, context: TranspileContext): string {
    const data = node.data as { condition?: Condition | null; isInfinite?: boolean };
    const childContext: TranspileContext = {
      ...context,
      indent: context.indent + 1,
      loopDepth: context.loopDepth + 1
    };
    const body = this.walkNodes(node.children || [], childContext) || `${this.pad(childContext)}pass`;

    if (data.isInfinite) return `${this.pad(context)}while True:\n${body}`;
    return `${this.pad(context)}while ${this.buildCondition(data.condition, context)}:\n${body}`;
  }

  private handleFor(node: ASTNode, context: TranspileContext): string {
    const data = node.data as {
      subType?: 'range' | 'iterable';
      iterName?: string;
      start?: number;
      end?: number;
      iterableVarId?: string;
    };
    const iterator = this.sanitizeName(data.iterName || 'i');
    const childContext: TranspileContext = {
      ...context,
      indent: context.indent + 1,
      loopDepth: context.loopDepth + 1
    };
    const body = this.walkNodes(node.children || [], childContext) || `${this.pad(childContext)}pass`;

    const header = data.subType === 'iterable'
      ? `for ${iterator} in ${this.resolveName(data.iterableVarId || '', context)}:`
      : `for ${iterator} in range(${data.start ?? 0}, ${data.end ?? 0}):`;

    return `${this.pad(context)}${header}\n${body}`;
  }

  private handleLoop(node: ASTNode, context: TranspileContext): string {
    const childContext: TranspileContext = {
      ...context,
      indent: context.indent + 1,
      loopDepth: context.loopDepth + 1
    };
    const body = this.walkNodes(node.children || [], childContext) || `${this.pad(childContext)}pass`;
    return `${this.pad(context)}while True:\n${body}`;
  }

  private handleBreak(node: ASTNode, context: TranspileContext): string {
    if (!context.loopDepth) {
      return `${this.pad(context)}pass  # [CodeFlow] 'romper' ignorado: no está dentro de un bucle`;
    }
    return `${this.pad(context)}break`;
  }

  private handleFunctionCall(node: ASTNode, context: TranspileContext): string {
    const data = node.data as { funcName?: string; argVarId?: string | null; targetVarId?: string | null };
    const name = this.sanitizeName(data.funcName || 'func');
    const argument = data.argVarId ? this.resolveName(data.argVarId, context) : '';
    const call = `${name}(${argument})`;

    if (data.targetVarId) {
      return `${this.pad(context)}${this.resolveName(data.targetVarId, context)} = ${call}`;
    }
    return `${this.pad(context)}${call}`;
  }

  private buildCondition(condition: Condition | null | undefined, context: TranspileContext): string {
    if (!condition) return 'True';
    const left = this.resolveName(condition.leftVarId, context);
    const operator = condition.operator || '==';
    const right = condition.rightType === 'variable'
      ? this.resolveName(condition.rightVarId || '', context)
      : this.pyLiteral(condition.leftType || 'string', condition.rightValue);
    return `${left} ${operator} ${right}`;
  }

  private pad(context: TranspileContext): string {
    return INDENT.repeat(context.indent);
  }

  private resolveName(id: string, context: TranspileContext): string {
    if (!id) return '_undefined_';
    const variable = context.varMap.get(id);
    return variable ? this.sanitizeName(variable.name) : '_undefined_';
  }

  private resolveType(id: string, context: TranspileContext): VariableType {
    if (!id) return 'string';
    return context.varMap.get(id)?.type || 'string';
  }

  private pyLiteral(type: VariableType, value: unknown): string {
    if (type === 'boolean') return value === true || value === 'true' ? 'True' : 'False';
    if (type === 'number') {
      const number = Number(value);
      return Number.isFinite(number) ? String(number) : '0';
    }
    if (type === 'list') return '[]';
    if (value === null || value === undefined) return '""';
    return `"${this.escapePyString(String(value))}"`;
  }

  private sanitizeName(name: string): string {
    if (!name) return '_var';
    let clean = String(name)
      .replace(/[\s-]/g, '_')
      .replace(/[^a-zA-Z0-9_]/g, '')
      .replace(/^(\d)/, '_$1');
    if (!clean) clean = '_var';
    if (PYTHON_KEYWORDS.has(clean)) clean += '_var';
    return clean;
  }

  private escapePyString(value: string): string {
    return String(value ?? '')
      .replace(/\\/g, '\\\\')
      .replace(/"/g, '\\"')
      .replace(/\r/g, '\\r')
      .replace(/\n/g, '\\n');
  }
}
